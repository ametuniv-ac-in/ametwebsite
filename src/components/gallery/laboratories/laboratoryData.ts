// Group labs by course
export const groupLabsByCourse = () => {
  const groupedLabs = laboratoryList.reduce((acc, lab) => {
    if (!acc[lab.course]) {
      acc[lab.course] = [];
    }
    acc[lab.course].push(lab);
    return acc;
  }, {} as Record<string, LabData[]>);

  // Get unique course names
  const courses = Object.keys(groupedLabs);
  
  return { groupedLabs, courses };
};
